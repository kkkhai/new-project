"""Regenerate src/game/art/generated.ts from the drawing scripts in this folder.

Usage: python3 tools/art/build.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import explorer  # noqa: E402
import jungle  # noqa: E402
import boulder  # noqa: E402
import import_images  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'game', 'art', 'generated.ts')


def sprite(palette, frames):
    return {'size': 32, 'palette': palette, 'frames': frames}


def main():
    data = {
        'EXPLORER_32': sprite(explorer.PALETTE, explorer.frames()),
        'JUNGLE_TILES': sprite(jungle.PALETTE, jungle.frames()),
    }
    # Items converted from the owner's images (tools/art/source) plus the drawn boulder.
    items = import_images.build()
    items['boulder'] = boulder.sprite()
    for kind, d in items.items():
        data[f'ITEM_{kind}'] = d
    lines = [
        '// GENERATED by tools/art/build.py from tools/art/*.py. Do not edit by hand.',
        "import type { SpriteDef } from '../spriteData.ts';",
        '',
    ]
    for name, d in data.items():
        lines.append(f'export const {name}: SpriteDef = {json.dumps(d, indent=1)};')
        lines.append('')
    lines.append(f'export const EXPLORER_32_COSTUME: Record<string, string> = {json.dumps(explorer.COSTUME, indent=1)};')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {os.path.relpath(OUT)}')


if __name__ == '__main__':
    main()
